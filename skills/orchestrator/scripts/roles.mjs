#!/usr/bin/env node
// Writes the orchestrator's subagent definitions for your agent(s), from ../roles/*.md. Zero dependencies.
//   node roles.mjs --agent claude                      user-level: ~/.claude/agents/
//   node roles.mjs --agent codex --agent opencode      ~/.codex/agents/, ~/.config/opencode/agents/
//   node roles.mjs --agent claude --project .          this repo only: ./.claude/agents/
//   node roles.mjs --agent codex --model worker=<id> --model redteam=<id>
// Roles: researcher, redteam, rescue, worker (quick uses the worker model). Claude Code defaults come from
// the role files; other agents use their own default model unless you pass --model.
// Safe to re-run: it rewrites only files it generated and leaves hand-written ones alone.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

export const ROLES_DIR = path.resolve(import.meta.dirname, "..", "roles");
export const AGENTS = ["claude", "codex", "opencode"];
const GENERATED = "generated by the orchestrator skill's scripts/roles.mjs from its roles/; edit those and re-run";

const ok = (m) => console.log(`  ok   ${m}`);
const warn = (m) => console.log(`  WARN ${m}`);

function parseRole(text) {
  const m = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(text.replace(/\r\n/g, "\n"));
  if (!m) throw new Error("role file has no frontmatter");
  const meta = {};
  for (const line of m[1].split("\n")) {
    const i = line.indexOf(":");
    if (i > 0) meta[line.slice(0, i).trim()] = line.slice(i + 1).trim();
  }
  return { meta, body: m[2].trim() };
}

/** Which model key a role file uses: researcher, redteam, rescue or worker. */
export const roleOf = (name) => (name === "orchestrator-quick" ? "worker" : name.replace("orchestrator-", ""));
const readOnly = (meta) => Boolean(meta.tools) && !/\b(Write|Edit)\b/.test(meta.tools);
const PORTABLE_WORKTREE =
  "\n\nWorktree: your agent does not create one for you. If `git rev-parse --show-toplevel` is the main checkout, first run `git worktree add .claude/worktrees/<task id> -b orch/<task id> <base branch>` and work only there.";

export function renderRole(agent, text, model) {
  const { meta, body } = parseRole(text);
  const portableBody = (meta.isolation === "worktree" ? body + PORTABLE_WORKTREE : body).replaceAll("CLAUDE.md", "AGENTS.md");
  if (agent === "claude") {
    const fm = Object.entries({ ...meta, ...(model ? { model } : {}) }).map(([k, v]) => `${k}: ${v}`);
    return `---\n${fm.join("\n")}\n---\n${body}\n\n<!-- ${GENERATED} -->\n`;
  }
  if (agent === "codex") {
    return [
      `# ${GENERATED}`,
      `name = ${JSON.stringify(meta.name)}`,
      `description = ${JSON.stringify(meta.description)}`,
      ...(model ? [`model = ${JSON.stringify(model)}`] : []),
      ...(readOnly(meta) ? ['sandbox_mode = "read-only"'] : []),
      `developer_instructions = '''\n${portableBody}\n'''`,
      "",
    ].join("\n");
  }
  return [
    "---",
    `description: ${JSON.stringify(meta.description)}`,
    "mode: subagent",
    ...(model ? [`model: ${model}`] : []),
    ...(readOnly(meta) ? ["permissions:", "  - action: edit", '    resource: "*"', "    effect: deny"] : []),
    "---",
    portableBody,
    "",
    `<!-- ${GENERATED} -->`,
    "",
  ].join("\n");
}

/** Where an agent's role files go: under a project folder, or the agent's user-level config. */
export function targetDir(agent, project) {
  if (project) return path.join(project, { claude: ".claude", codex: ".codex", opencode: ".opencode" }[agent], "agents");
  const home = os.homedir();
  return { claude: path.join(home, ".claude", "agents"), codex: path.join(home, ".codex", "agents"), opencode: path.join(home, ".config", "opencode", "agents") }[agent];
}

/** Writes every role for each agent. `models` is { agent: { role: id } }; a blank id keeps the default. */
export function writeRoles({ agents, project, models = {} }) {
  for (const agent of agents) {
    if (!AGENTS.includes(agent)) throw new Error(`unknown agent "${agent}"; use ${AGENTS.join(", ")}`);
    const dir = targetDir(agent, project);
    fs.mkdirSync(dir, { recursive: true });
    for (const file of fs.readdirSync(ROLES_DIR).filter((f) => f.endsWith(".md"))) {
      const name = file.slice(0, -3);
      const out = path.join(dir, `${name}${agent === "codex" ? ".toml" : ".md"}`);
      if (fs.existsSync(out) && !fs.readFileSync(out, "utf8").includes(GENERATED)) {
        warn(`${out} is hand-written; left alone (delete it to regenerate)`);
        continue;
      }
      fs.writeFileSync(out, renderRole(agent, fs.readFileSync(path.join(ROLES_DIR, file), "utf8"), models[agent]?.[roleOf(name)] || ""));
      ok(out);
    }
  }
}

if (import.meta.main ?? process.argv[1] === import.meta.filename) {
  const agents = [];
  const pinned = {};
  let project;
  const argv = process.argv.slice(2);
  for (let i = 0; i < argv.length; i++) {
    const [flag, value] = [argv[i], argv[i + 1]];
    if (flag === "--agent") agents.push(value);
    else if (flag === "--project") project = path.resolve(value);
    else if (flag === "--model" && /^[a-z]+=.+$/.test(value ?? "")) pinned[value.split("=")[0]] = value.slice(value.indexOf("=") + 1);
    else { console.error(`unknown or incomplete option ${flag}; see the header of ${import.meta.filename}`); process.exit(2); }
    i++;
  }
  if (agents.length === 0) agents.push("claude");
  writeRoles({ agents, project, models: Object.fromEntries(agents.map((a) => [a, pinned])) });
}
