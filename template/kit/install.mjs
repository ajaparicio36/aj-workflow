#!/usr/bin/env node
// Wires the hub into the workspace (the parent folder of this hub). Safe to re-run; run it after
// pulling kit changes or editing workflow.config.json.
//   node kit/install.mjs [--workspace <dir>]
// - renders "How work runs" in AGENTS.md from workflow.config.json
// - links kit/skills/* into each agent's workspace skills folder (junction on Windows, no admin needed)
// - orchestrated mode: writes the orchestrator role files for each agent, with the configured models
// - links AGENTS.md (and CLAUDE.md for Claude Code) into the workspace root (copy if symlinks are not allowed)
// - Claude Code: <workspace>/.claude/settings.json with worktree.baseRef head (written only if missing)
// - turns on the hub's pre-commit hook (core.hooksPath .githooks)
import { execFileSync, execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const KB = path.resolve(import.meta.dirname, "..");
const AGENTS = ["claude", "codex", "opencode"];
const ROLES = ["lead", "researcher", "redteam", "rescue", "worker"];
const GENERATED = "generated by kit/install.mjs from kit/skills/orchestrator/roles; edit those and re-run";

const ok = (m) => console.log(`  ok   ${m}`);
const warn = (m) => console.log(`  WARN ${m}`);

export function readConfig(file) {
  const c = JSON.parse(fs.readFileSync(file, "utf8"));
  const fail = (m) => { throw new Error(`${file}: ${m}`); };
  for (const k of ["name", "owner", "hub", "ticketKey"]) if (typeof c[k] !== "string" || !c[k].trim()) fail(`"${k}" must be a non-empty string`);
  if (typeof c.repos !== "object" || c.repos === null || Object.keys(c.repos).length === 0) fail(`"repos" must map label keys to repo names`);
  if (!Array.isArray(c.agents) || c.agents.length === 0 || c.agents.some((a) => !AGENTS.includes(a))) fail(`"agents" must list some of ${AGENTS.join(", ")}`);
  if (!["orchestrated", "solo"].includes(c.mode)) fail(`"mode" must be "orchestrated" or "solo"`);
  c.models ??= {};
  return c;
}

const modelOf = (c, agent, role) => c.models?.[agent]?.[role] || "";
const shown = (m) => (m ? `\`${m}\`` : "agent default");

export function modeSection(c) {
  const cols = c.agents;
  if (c.mode === "solo") {
    return [
      "Mode: **solo** (from `workflow.config.json`). One model does the whole loop in this session; no subagents.",
      "",
      "1. Research: the ticket, `CONTEXT.md`, matching notes, then the code (through CodeGraph when the repo has an index). For multi-file work, write what you found to `.orchestrator/research.md`.",
      "2. Spec and plan (multi-file work): `.orchestrator/spec.md` with goal, non-goals, exact contracts and acceptance criteria, then an ordered task list where each task names its files and a verify command.",
      "3. Build task by task, in order, on the ticket branch. Run the task's verify command before the next one; commit per task.",
      "4. Red-team yourself before shipping: re-read the spec and diff looking for races, missing edge cases and contracts that disagree. Fix what you find.",
      "5. Final gate: the repo's full typecheck, lint and tests, then QA.",
      "",
      `Model: ${cols.map((a) => `${a} ${shown(modelOf(c, a, "lead"))}`).join(", ")}.`,
    ].join("\n");
  }
  const what = {
    lead: "the session you talk to: plans, writes spec and DAG, merges waves",
    researcher: "maps the code into `.orchestrator/research.md`",
    redteam: "attacks the spec and plan before code is written",
    rescue: "root-causes a worker that failed its check twice",
    worker: "one task in its own worktree, verified and committed",
  };
  const rows = ROLES.map((r) => `| ${r} | ${what[r]} | ${cols.map((a) => shown(modelOf(c, a, r))).join(" | ")} |`);
  const files = { claude: "`.claude/agents/`", codex: "`.codex/agents/`", opencode: "`.opencode/agents/`" };
  return [
    "Mode: **orchestrated** (from `workflow.config.json`). The lead plans and reviews; research, edits and adversarial review go to subagents with their own models, through the `orchestrator` skill. One-file changes take its quick path.",
    "",
    `| Role | Job | ${cols.join(" | ")} |`,
    `|---|---|${cols.map(() => "---|").join("")}`,
    ...rows,
    "",
    `The lead runs on whatever model you start the session with. The other roles are set in the role files \`kit/install.mjs\` writes (${cols.map((a) => files[a]).join(", ")}).`,
    "",
    "Orchestrator preflight, once per code repo: a CodeGraph index (`codegraph init -i` in the repo root), and `.orchestrator/`, `.codegraph/`, `.claude/worktrees/` in `.gitignore`." +
      (cols.includes("claude")
        ? " Claude Code reads `worktree.baseRef` only from the folder the session started in; the installer writes it to `<workspace>/.claude/settings.json`, so start sessions at the workspace root."
        : ""),
  ].join("\n");
}

export function renderAgentsMd(text, c) {
  const re = /(<!-- aj:mode:start -->\n)[\s\S]*?(\n<!-- aj:mode:end -->)/;
  if (!re.test(text)) throw new Error("AGENTS.md has no <!-- aj:mode:start --> ... <!-- aj:mode:end --> block");
  return text.replace(re, (_m, a, b) => `${a}${modeSection(c)}${b}`);
}

function parseRole(text) {
  const m = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(text.replace(/\r\n/g, "\n"));
  if (!m) throw new Error("role file has no frontmatter");
  const meta = {};
  for (const line of m[1].split("\n")) {
    const i = line.indexOf(":");
    if (i > 0) meta[line.slice(0, i).trim()] = line.slice(i + 1).trim();
  }
  return { meta, body: m[2].trim() };
}

const roleOf = (name) => (name === "orchestrator-quick" ? "worker" : name.replace("orchestrator-", ""));
const readOnly = (meta) => Boolean(meta.tools) && !/\b(Write|Edit)\b/.test(meta.tools);
const PORTABLE_WORKTREE =
  "\n\nWorktree: your agent does not create one for you. If `git rev-parse --show-toplevel` is the main checkout, first run `git worktree add .claude/worktrees/<task id> -b orch/<task id> <base branch>` and work only there.";

export function renderRole(agent, text, model) {
  const { meta, body } = parseRole(text);
  const portableBody = (meta.isolation === "worktree" ? body + PORTABLE_WORKTREE : body).replaceAll("CLAUDE.md", "AGENTS.md");
  if (agent === "claude") {
    const fm = Object.entries({ ...meta, ...(model ? { model } : {}) }).map(([k, v]) => `${k}: ${v}`);
    return `---\n${fm.join("\n")}\n---\n${body}\n\n<!-- ${GENERATED} -->\n`;
  }
  if (agent === "codex") {
    return [
      `# ${GENERATED}`,
      `name = ${JSON.stringify(meta.name)}`,
      `description = ${JSON.stringify(meta.description)}`,
      ...(model ? [`model = ${JSON.stringify(model)}`] : []),
      ...(readOnly(meta) ? ['sandbox_mode = "read-only"'] : []),
      `developer_instructions = '''\n${portableBody}\n'''`,
      "",
    ].join("\n");
  }
  return [
    "---",
    `description: ${JSON.stringify(meta.description)}`,
    "mode: subagent",
    ...(model ? [`model: ${model}`] : []),
    ...(readOnly(meta) ? ["permissions:", "  - action: edit", '    resource: "*"', "    effect: deny"] : []),
    "---",
    portableBody,
    "",
    `<!-- ${GENERATED} -->`,
    "",
  ].join("\n");
}

const ROLE_TARGET = {
  claude: (ws, n) => path.join(ws, ".claude", "agents", `${n}.md`),
  codex: (ws, n) => path.join(ws, ".codex", "agents", `${n}.toml`),
  opencode: (ws, n) => path.join(ws, ".opencode", "agents", `${n}.md`),
};

/** Writes a generated file unless a hand-written one is there. */
function writeGenerated(file, text) {
  if (fs.existsSync(file) && !fs.readFileSync(file, "utf8").includes(GENERATED)) return warn(`${file} is hand-written; left alone`);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
  ok(path.relative(process.cwd(), file) || file);
}

function sameTarget(a, b) {
  try { return fs.realpathSync(a) === fs.realpathSync(b); } catch { return false; }
}

function linkDir(src, dst) {
  const st = fs.lstatSync(dst, { throwIfNoEntry: false });
  if (st?.isSymbolicLink() && sameTarget(dst, src)) return ok(`${path.basename(dst)} (linked)`);
  if (st && !st.isSymbolicLink()) return warn(`${dst} exists and is not a link; left alone`);
  if (st) fs.unlinkSync(dst);
  fs.symlinkSync(src, dst, "junction");
  ok(path.basename(dst));
}

function unlinkOurs(src, dst) {
  const st = fs.lstatSync(dst, { throwIfNoEntry: false });
  if (st?.isSymbolicLink() && sameTarget(dst, src)) { fs.unlinkSync(dst); ok(`${path.basename(dst)} unlinked (solo mode)`); }
}

function linkFile(src, dst) {
  const st = fs.lstatSync(dst, { throwIfNoEntry: false });
  if (st?.isSymbolicLink() && sameTarget(dst, src)) return ok(`${path.basename(dst)} (linked)`);
  if (st && !st.isSymbolicLink() && fs.readFileSync(dst, "utf8") !== fs.readFileSync(src, "utf8") && !fs.existsSync(`${dst}.bak`)) {
    fs.copyFileSync(dst, `${dst}.bak`);
    warn(`kept your old ${path.basename(dst)} as ${path.basename(dst)}.bak`);
  }
  if (st) fs.rmSync(dst, { force: true });
  try {
    fs.symlinkSync(src, dst, "file");
    ok(`${path.basename(dst)} (symlink)`);
  } catch {
    fs.copyFileSync(src, dst);
    warn(`${path.basename(dst)} copied (symlinks need Developer Mode on Windows); re-run install.mjs after editing the hub copy`);
  }
}

function has(cmd) {
  try { execSync(`${cmd} --version`, { stdio: "ignore" }); return true; } catch { return false; }
}

export function install(workspace) {
  const c = readConfig(path.join(KB, "workflow.config.json"));
  const agentsMd = path.join(KB, "AGENTS.md");
  fs.writeFileSync(agentsMd, renderAgentsMd(fs.readFileSync(agentsMd, "utf8"), c));
  console.log(`AGENTS.md: How work runs = ${c.mode}, agents ${c.agents.join(", ")}`);

  // Claude Code and OpenCode read .claude/skills; Codex (and OpenCode) read .agents/skills.
  const skillDirs = new Set();
  if (c.agents.includes("claude")) skillDirs.add(path.join(workspace, ".claude", "skills"));
  if (c.agents.includes("codex") || (c.agents.includes("opencode") && !c.agents.includes("claude"))) skillDirs.add(path.join(workspace, ".agents", "skills"));
  const kitSkills = path.join(KB, "kit", "skills");
  for (const dir of skillDirs) {
    console.log(`Skills -> ${dir}`);
    fs.mkdirSync(dir, { recursive: true });
    for (const name of fs.readdirSync(kitSkills)) {
      const src = path.join(kitSkills, name);
      if (name === "orchestrator" && c.mode === "solo") unlinkOurs(src, path.join(dir, name));
      else linkDir(src, path.join(dir, name));
    }
  }

  if (c.mode === "orchestrated") {
    console.log("Orchestrator roles");
    const rolesDir = path.join(kitSkills, "orchestrator", "roles");
    for (const file of fs.readdirSync(rolesDir).filter((f) => f.endsWith(".md"))) {
      const name = file.slice(0, -3);
      const text = fs.readFileSync(path.join(rolesDir, file), "utf8");
      for (const agent of c.agents) writeGenerated(ROLE_TARGET[agent](workspace, name), renderRole(agent, text, modelOf(c, agent, roleOf(name))));
    }
  }

  console.log(`Workspace docs -> ${workspace}`);
  linkFile(agentsMd, path.join(workspace, "AGENTS.md"));
  if (c.agents.includes("claude")) linkFile(path.join(KB, "CLAUDE.md"), path.join(workspace, "CLAUDE.md"));

  if (c.agents.includes("claude")) {
    // Claude Code reads project settings only from the session's start folder.
    const settings = path.join(workspace, ".claude", "settings.json");
    if (!fs.existsSync(settings)) {
      fs.mkdirSync(path.dirname(settings), { recursive: true });
      fs.writeFileSync(settings, '{ "worktree": { "baseRef": "head" } }\n');
      ok("settings.json (worktree.baseRef head)");
    } else {
      let baseRef;
      try { baseRef = JSON.parse(fs.readFileSync(settings, "utf8"))?.worktree?.baseRef; } catch { baseRef = undefined; }
      if (baseRef === "head") ok("settings.json (worktree.baseRef head)");
      else warn(`${settings} lacks worktree.baseRef head; add it or worker worktrees branch from origin/main`);
    }
  }

  if (fs.existsSync(path.join(KB, ".git"))) {
    fs.chmodSync(path.join(KB, ".githooks", "pre-commit"), 0o755); // git skips a hook without the exec bit
    execFileSync("git", ["-C", KB, "config", "core.hooksPath", ".githooks"]);
    ok("hooks (core.hooksPath .githooks)");
  } else warn("hub is not a git repo yet; run `git init` there, then re-run install.mjs for the pre-commit hook");

  console.log("Checks");
  for (const cmd of ["gh", "git"]) has(cmd) ? ok(cmd) : warn(`${cmd} missing`);
  if (c.mode === "orchestrated") has("codegraph") ? ok("codegraph") : warn("codegraph missing (optional, strongly advised): npx @colbymchenry/codegraph");
}

if (import.meta.main ?? process.argv[1] === import.meta.filename) {
  const i = process.argv.indexOf("--workspace");
  install(path.resolve(i > 0 ? process.argv[i + 1] : path.dirname(KB)));
}
